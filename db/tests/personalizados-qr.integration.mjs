import fs from 'node:fs/promises';
import assert from 'node:assert/strict';

export async function testPersonalizadosQr(db,{login,stock,count,uid}) {
  const fixture=JSON.parse(await fs.readFile(new URL('./personalizados_compra.fixture.json',import.meta.url),'utf8'));
  const columnas=fixture.columnas.map(c=>`"${c.name}" ${c.type}${c.name==='id'?' generated by default as identity primary key':c.default?` default ${c.default}`:''}${c.notnull?' not null':''}`);
  await db.exec(`create table public.compra_solicitud(${columnas.join(',')});
    create table if not exists public.pedido_evento(id bigint generated by default as identity,pedido_id bigint,accion text,motivo text,usuario text);
    grant select,insert,update on public.compra_solicitud,public.pedido_evento to authenticated;
    grant usage,select on all sequences in schema public to authenticated;`);
  for(const f of fixture.funciones)await db.exec(f);
  // Función de permisos vigente; los perfiles se autentican con los mismos
  // roles reales del resto de la prueba de integración.
  await db.exec(`create or replace function public.app_puede_inventariar() returns boolean
    language sql stable security definer set search_path=public as $$
      select exists(select 1 from public.perfil where id=auth.uid() and activo and rol<>'cajero');
    $$;`);
  await db.exec(`create trigger trg_compra_solicitud_sync after insert or update of estado on public.pedido_linea
    for each row execute function public._compra_solicitud_sync();`);
  // Historial realmente entregado: la migración no debe reabrir ni alterar nada.
  await db.exec(`insert into pedido(id,categoria,numero) values(910,'TIENDA','QA-PERSONALIZADOS'),(911,'TIENDA','QA-MIXTO'),(912,'TIENDA','QA-HISTORICO');
    insert into pedido_linea(id,pedido_id,es_personalizado,descripcion,unidad_medida,cantidad_base,estado,sucursal_origen_id)
      values(9101,910,true,'Escobas especiales QA','unidad',6,'ESPECIAL',1),
      (9111,911,true,'Servicio especial QA','unidad',2,'ESPECIAL',1),
      (9121,912,true,'Histórico entregado QA','unidad',3,'COMPRADO_DIRECTO',1);
    update pedido set estado='COMPLETADO' where id=912;`);
  const historico=(await db.query('select to_jsonb(l) l from pedido_linea l where id=9121')).rows[0].l;
  await db.exec(await fs.readFile(new URL('../../supabase/migrations/20261023151816_personalizados_conducto_regular_qr.sql',import.meta.url),'utf8'));
  assert.deepEqual((await db.query('select to_jsonb(l) l from pedido_linea l where id=9121')).rows[0].l,historico);
  const stockAntes=await stock(1),kardexAntes=await count('kardex_transacciones');
  await login(1);await db.exec('set role authenticated');
  // Ni el RPC antiguo ni el UPDATE usado por una pantalla vieja pueden cerrar
  // una línea antes de que exista preparación.
  await assert.rejects(()=>db.query("select comprar_directo(9101,'Proveedor QA',10,'QA')"),/miniapp/);
  await assert.rejects(()=>db.query("select entregar_personalizado(9101,'QA')"),/miniapp/);
  await assert.rejects(()=>db.query("update pedido_linea set estado='DESPACHADA' where id=9101"),/miniapp/);
  const solicitud=(await db.query('select id from compra_solicitud where pedido_linea_id=9101')).rows[0].id;
  const recibida=(await db.query('select recibir_compra($1,null,null,$2) r',[solicitud,'Prepara QA'])).rows[0].r;
  assert.equal(recibida.estado,'RECIBIDA');assert.equal(Number(recibida.cantidad_recibida),6);
  assert.equal((await db.query('select estado from pedido_linea where id=9101')).rows[0].estado,'ESPECIAL');
  assert.equal((await db.query('select estado from pedido where id=910')).rows[0].estado,'ABIERTO');
  assert.equal(await stock(1),stockAntes);assert.equal(await count('kardex_transacciones'),kardexAntes);

  let r;
  const operar=async(accion='consultar',datos={},version=r?.tarea.version)=>(await db.query('select operar_preparacion_pedido(910,1,null,$1,$2,$3) r',[accion,version||null,JSON.stringify(datos)])).rows[0].r;
  const foto=async id=>{
    const e=(await db.query("select operar_evidencia_operacion('PEDIDO',910,$1,'crear',$2) r",[r.tarea.id,JSON.stringify({id,version:r.tarea.version,cantidad:1})])).rows[0].r;
    await db.query("insert into storage.objects(bucket_id,name,metadata) values('evidencias_operaciones',$1,'{\"mimetype\":\"image/jpeg\",\"size\":512}')",[e.rutas[0]]);
    return id;
  };
  r=await operar('escanear');assert.equal(r.pedido_dos_actores,true);
  assert.equal(r.lineas[0].snapshot.es_personalizado,true);assert.equal(r.lineas[0].snapshot.preparable,true);
  r=await operar('guardar_preparacion',{linea_id:9101,cantidad_base:6});
  await assert.rejects(()=>operar('preparado'),/Adjunta fotos/);
  r=await operar('preparado',{evidencia_id:await foto('70000000-0000-0000-0000-000000000001')});
  await assert.rejects(()=>operar('tomar_revision'),/otra persona/);
  await login(2);r=await operar('escanear');
  r=await operar('guardar_revision',{linea_id:9101,cantidad_base:6,metodo:'visual'});
  assert.deepEqual(r.plan_salida[0].asignaciones,[]);assert.equal(r.plan_salida[0].error,null);
  await assert.rejects(()=>operar('confirmar_retiro',{destino:'Obra QA',plan:r.plan_salida}),/Adjunta fotos/);
  const salida={destino:'Obra QA',plan:r.plan_salida,evidencia_id:await foto('70000000-0000-0000-0000-000000000002')};
  const version=r.tarea.version;
  r=await operar('confirmar_retiro',salida);
  assert.equal(r.tarea.estado,'DESPACHADO');assert.equal(r.entregada,true);assert.equal(r.pedido.estado,'COMPLETADO');
  assert.equal(r.retiro.transportista_id,uid(2));
  const entregada=(await db.query('select estado,cantidad_despachada,modificado_por from pedido_linea where id=9101')).rows[0];
  assert.equal(entregada.estado,'DESPACHADA');assert.equal(Number(entregada.cantidad_despachada),6);assert.equal(entregada.modificado_por,'Verifica QA');
  await operar('confirmar_retiro',salida,version);
  assert.equal(await stock(1),stockAntes);assert.equal(await count('kardex_transacciones'),kardexAntes);
  await db.exec('reset role');
  assert.equal((await db.query('select count(*) n from evidencia_operacion.retiro where preparacion_id=$1',[r.tarea.id])).rows[0].n,1);
  const mensajes=(await db.query("select etapa,mensajes from evidencia_operacion.lote where documento_id=910 order by creado_en")).rows;
  assert.equal(mensajes.length,2);assert.match(mensajes[0].mensajes.join('\n'),/Escobas especiales QA/);assert.match(mensajes[1].mensajes.join('\n'),/salen 6 de 6/);
  // Mixto: entregar catálogo no elimina el personalizado pendiente.
  await db.exec(`insert into pedido_linea(id,pedido_id,producto_id,presentacion_id,cantidad_base,cantidad_despachada,estado,sucursal_origen_id)
    values(9112,911,1,1,1,1,'DESPACHADA',1);`);
  const pendientes=(await db.query('select * from almacen_operaciones.lineas_actuales(911,1)')).rows;
  assert.equal(pendientes.length,1);assert.equal(pendientes[0].linea_id,9111);
  console.log('OK: personalizados por QR, compra separada, dos responsables y fotos, retiro único sin Kardex, mixtos e históricos');
}
