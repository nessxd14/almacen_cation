import fs from 'node:fs/promises';

// Estructura obtenida por lectura de catálogos, sin filas del negocio.
export async function crearEsquemaConteo(db) {
  const fixture = JSON.parse(await fs.readFile(new URL('./conteo-controlado.fixture.json', import.meta.url), 'utf8'));
  const quote = s => '"' + s.replaceAll('"', '""') + '"';
  await db.exec(`create role anon; create role authenticated;
    create schema auth;create schema storage;
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    create function auth.jwt() returns jsonb language sql stable as $$select jsonb_build_object('sub',auth.uid())$$;
    grant usage on schema auth to authenticated,anon;
    set check_function_bodies=false;`);
  for (const e of fixture.enums) await db.exec(`create type ${quote(e.name)} as enum(${e.values.map(v => "'" + v.replaceAll("'", "''") + "'").join(',')});`);
  for (const t of fixture.tables) {
    const cols = t.columns.map(c => quote(c.name) + ' ' + c.type +
      (c.identity || c.default?.startsWith('nextval(') ? ' generated by default as identity' : c.generated ? ' generated always as (' + c.default + ') stored' : c.default ? ' default ' + c.default : '') + (c.notnull ? ' not null' : ''));
    await db.exec(`create table public.${quote(t.name)}(${cols.join(',')});`);
    for (const c of t.constraints || []) await db.exec(`alter table public.${quote(t.name)} add constraint ${quote(c.name)} ${c.definition};`);
  }
  for (const f of fixture.functions) await db.exec(f + ';');
  for (const t of fixture.triggers) await db.exec(t + ';');
  await db.exec(`set check_function_bodies=true;
    alter table sesion_conteo enable row level security;
    alter table conciliacion_linea enable row level security;
    create policy auth_all on sesion_conteo for all to authenticated using(true) with check(true);
    create policy auth_all on conciliacion_linea for all to authenticated using(true) with check(true);
    create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    create table storage.objects(bucket_id text,name text,owner_id text,primary key(bucket_id,name));
    alter table storage.objects enable row level security;
    grant usage on schema storage to authenticated;
    grant select,insert,update,delete on storage.objects to authenticated;
    grant usage on schema public to authenticated;
    grant all on all tables in schema public to authenticated;
    grant usage,select on all sequences in schema public to authenticated;`);
}
