  await db.exec(`create schema storage;
    create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
    create table storage.objects(id uuid default gen_random_uuid(),bucket_id text,name text,metadata jsonb,unique(bucket_id,name));
    alter table storage.objects enable row level security;
    grant usage on schema storage to authenticated; grant insert on storage.objects to authenticated;`);
  await db.exec(await fs.readFile(new URL('../../supabase/migrations/20261019221227_evidencia_vtd_telegram.sql', import.meta.url), 'utf8'));
  await db.exec(await fs.readFile(new URL('../../supabase/migrations/20261019222415_invocacion_vtd_un_solo_uso.sql', import.meta.url), 'utf8'));
  await db.exec(await fs.readFile(new URL('../../supabase/migrations/20261019222755_espera_worker_vtd_telegram.sql', import.meta.url), 'utf8'));
  await db.exec(`update evidencia_vtd.configuracion set activo=true;
    insert into venta(id,ubicacion_id,numero,subtotal,total,cobro_exigible,sesion_caja_id) values(702,4,'VTD-QA-EVIDENCIA',10,10,true,1);
    insert into venta_linea(id,venta_id,producto_id,presentacion_id,cantidad,cantidad_presentacion,precio_lista,precio_unitario) values(702,702,1,1,1,1,10,10);`);
  const operacion = '20000000-0000-0000-0000-000000000003';
  const rpc = async (accion, datos = {}) => (await db.query('select operar_caja_almacen($1,$2,1,$3) r', [accion, operacion, JSON.stringify(datos)])).rows[0].r;
  const evidencia = async (accion, datos = {}) => (await db.query('select operar_evidencia_vtd($1,702,$2) r', [accion, JSON.stringify(datos)])).rows[0].r;
  const worker = async (accion, datos = {}) => (await db.query('select worker_evidencia_vtd($1,$2) r', [accion, JSON.stringify(datos)])).rows[0].r;
  const loteId = '30000000-0000-0000-0000-000000000001';
  await login(7); await rpc('vincular', { vtd_ids: [702], borrador: { cart: [] } });
  await login(1); await db.exec('set role authenticated');
  let r = await rpc('escanear', { venta_id: 702 });
  const version = r.vtds[0].version;
  const salida = { venta_id: 702, version, cantidades: [{ linea_id: 702, cantidad_base: 1 }] };
  const antes = await stock(1), kardex = await count('kardex_transacciones');
  await assert.rejects(() => rpc('enviar', salida), /Adjunta al menos una foto/);
  assert.equal(await stock(1), antes);
  await assert.rejects(() => db.query("select caja_almacen.operar('enviar',null,null,'{}')"), /permission denied/);
  await assert.rejects(() => db.query('select * from evidencia_vtd.configuracion'), /permission denied/);
  await assert.rejects(() => worker('reclamar'), /permission denied/);
  await assert.rejects(() => evidencia('crear', { id: loteId, version, cantidad: 0 }), /entre 1 y 10/);
  await assert.rejects(() => evidencia('crear', { id: loteId, version: version + 1, cantidad: 1 }), /entrega cambió/);
  const lote = await evidencia('crear', { id: loteId, version, cantidad: 2 });
  assert.equal(lote.rutas.length, 2); assert.deepEqual(lote.subidas, []);
  assert(lote.rutas.every(p => p.startsWith(uid(1) + '/' + loteId + '/')));
  await assert.rejects(() => rpc('enviar', { ...salida, evidencia_id: loteId }), /Faltan fotos/);
  const upload = ruta => db.query("insert into storage.objects(bucket_id,name,metadata) values('evidencias_vtd',$1,'{\"mimetype\":\"image/jpeg\",\"size\":512}')", [ruta]);
  await assert.rejects(() => upload(uid(1) + '/inventada/1.jpg'), /row-level security/);
  await login(2); await assert.rejects(() => upload(lote.rutas[0]), /row-level security/);
  await assert.rejects(() => rpc('enviar', { ...salida, evidencia_id: loteId }), /Adjunta al menos una foto/);
  await login(5); await assert.rejects(() => evidencia('consultar'), /otra sucursal/);
  await login(1); await upload(lote.rutas[0]);
  await assert.rejects(() => rpc('enviar', { ...salida, evidencia_id: loteId }), /Faltan fotos/);
  await upload(lote.rutas[1]);
  assert.equal((await evidencia('crear', { id: loteId, version, cantidad: 2 })).subidas.length, 2);
  const borradorViejoId = '30000000-0000-0000-0000-000000000002';
  const viejo = await evidencia('crear', { id: borradorViejoId, version, cantidad: 1 });
  await upload(viejo.rutas[0]);
  await db.exec('reset role');
  await db.query("update evidencia_vtd.lote set creado_en=now()-interval '49 hours' where id=$1", [borradorViejoId]);
  await db.exec('set role service_role');
  assert.equal((await worker('limpiar'))[0].id, borradorViejoId);
  await db.exec('reset role;set role authenticated');
  await assert.rejects(() => rpc('enviar', { ...salida, evidencia_id: borradorViejoId }), /Adjunta al menos una foto/, 'La limpieza reserva el borrador antes de borrar sus fotos');
  await db.exec('reset role;set role service_role'); await worker('borrado', { id: borradorViejoId });
  await db.exec('reset role;set role authenticated');
  await assert.rejects(() => db.exec('delete from storage.objects'), /permission denied/);
  r = await rpc('enviar', { ...salida, evidencia_id: loteId });
  assert.equal(r.vtds[0].estado, 'EN_CAJA'); assert.equal(await stock(1), antes - 1);
  assert.equal(await count('kardex_transacciones'), kardex + 1);
  assert.equal((await evidencia('consultar')).envios[0].estado, 'PENDIENTE');
  await rpc('enviar', salida);
  assert.equal(await count('kardex_transacciones'), kardex + 1, 'Una respuesta perdida no repite stock ni outbox');
  await assert.rejects(() => upload(lote.rutas[0]), /row-level security/);
  await db.exec('reset role;set role service_role');
  assert.equal((await worker('autorizar', { token: 'falso' })).autorizado, false);
  await db.exec('reset role');
  const nonce=(await db.query('insert into evidencia_vtd.invocacion default values returning id')).rows[0].id;
  await db.exec('set role service_role');
  assert.equal((await worker('autorizar', { token: nonce })).autorizado, true);
  assert.equal((await worker('autorizar', { token: nonce })).autorizado, false, 'Las invocaciones no se pueden reproducir');
  let trabajo = await worker('reclamar'); assert.equal(trabajo.id, loteId); assert.equal(await worker('reclamar'), null);
  const reserva = { id: loteId, lease: trabajo.lease };
  await assert.rejects(() => worker('confirmar', { ...reserva, telegram: [] }), /incompleta/);
  await assert.rejects(() => worker('confirmar', { ...reserva, lease: loteId, telegram: [] }), /reserva/);
  assert.deepEqual(await worker('limpiar'), []);
  await worker('error', { ...reserva, retry_after: 7200 });
  await db.exec('reset role');
  let raw = (await db.query('select * from evidencia_vtd.lote where id=$1', [loteId])).rows[0];
  assert.equal(raw.estado, 'PENDIENTE');
  assert(new Date(raw.proximo_intento) - new Date(raw.iniciado_en) >= 7199000, 'Se respeta retry_after');
  await db.exec("update evidencia_vtd.lote set proximo_intento=now()-interval '1 minute';set role service_role");
  trabajo = await worker('reclamar');
  await worker('incierto', { id: loteId, lease: trabajo.lease });
  assert.equal(await worker('reclamar'), null, 'Un timeout no repite mensajes a ciegas');
  assert.deepEqual(await worker('limpiar'), []);
  await db.exec('reset role');
  await login(1); await db.exec('set role authenticated');
  await assert.rejects(() => evidencia('reintentar', { id: loteId }), /error confirmado/);
  await db.exec("reset role;update evidencia_vtd.lote set estado='ERROR',intentos=5 where estado='INCIERTO';");
  await db.exec('set role authenticated'); await evidencia('reintentar', { id: loteId });
  await db.exec('reset role;set role service_role');
  trabajo = await worker('reclamar');
  const confirmacion = { id: loteId, lease: trabajo.lease, telegram: [{ message_id: 24529, file_id: 'qa-1' }, { message_id: 24530, file_id: 'qa-2' }] };
  await worker('confirmar', confirmacion); await worker('confirmar', confirmacion);
  assert.deepEqual(await worker('limpiar'), [], '48 horas contadas desde la confirmación, no desde la captura');
  await db.exec('reset role;set role authenticated');
  const estado = (await evidencia('consultar')).envios[0];
  assert.equal(estado.enlace, 'https://t.me/c/3058173908/17051/24529');
  await db.exec("reset role;update evidencia_vtd.lote set borrar_despues=now()-interval '1 second';set role service_role");
  assert.equal((await worker('limpiar')).length, 1);
  await worker('borrado', { id: loteId }); assert.deepEqual(await worker('limpiar'), []);
  await db.exec('reset role');
  assert.equal((await count('evidencia_vtd.lote')), 2);
  assert.equal((await db.query("select has_function_privilege('anon','operar_evidencia_vtd(text,bigint,jsonb)','execute') permitido")).rows[0].permitido, false);
  console.log('OK: foto obligatoria, objetos privados, sucursal/actor, sin doble stock, outbox, reservas, reintentos, timeout incierto y borrado sólo tras 48 h');
