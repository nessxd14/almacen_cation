import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { PGlite } from '@electric-sql/pglite';

// Esquema existente, datos sintéticos y la migración real. Ninguna conexión remota.
const fixture = JSON.parse(await fs.readFile(new URL('./flujos_qr.fixture.json', import.meta.url), 'utf8'));
const db = new PGlite();
const q = s => '"' + s.replaceAll('"', '""') + '"';
try {
  await db.exec(`create role anon;create role authenticated;create role service_role;
    create schema auth;create sequence traslado_grupo_seq;
    create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
    set check_function_bodies=false;`);
  for (const e of fixture.enums) await db.exec(`create type ${q(e.name)} as enum(${e.values.map(v => "'"+v.replaceAll("'","''")+"'").join(',')});`);
  for (const t of fixture.tables) {
    const cols = t.columns.map(c => q(c.name)+' '+c.type+
      (c.identity || c.default?.startsWith('nextval(') ? ' generated by default as identity' : c.generated ? ' generated always as ('+c.default+') stored' : c.default ? ' default '+c.default : '')+(c.notnull ? ' not null' : ''));
    await db.exec(`create table ${q(t.name)}(${cols.join(',')});`);
    for (const c of t.constraints || []) if (['p','u','c','x'].includes(c.type)) await db.exec(`alter table ${q(t.name)} add constraint ${q(c.name)} ${c.definition};`);
  }
  for (const f of fixture.functions) await db.exec(f+';');
  for (const t of fixture.triggers) await db.exec(t+';');
  await db.exec(await fs.readFile(new URL('../../supabase/migrations/20261020141453_fix_flujo_traslados.sql',import.meta.url),'utf8'));
  await db.exec(`grant usage on schema public,auth to authenticated;
    grant select,insert,update on all tables in schema public to authenticated;
    grant usage,select on all sequences in schema public to authenticated;
    insert into sucursal(id,nombre,tipo) values(1,'Origen QA','fisica'),(2,'Destino QA','fisica'),(3,'Ajena QA','fisica');
    insert into perfil(id,nombre,email,rol,sucursal_id) values
      ('00000000-0000-0000-0000-000000000001','Almacén QA','almacen@qa.invalid','almacenero',1),
      ('00000000-0000-0000-0000-000000000002','Vende QA','vende@qa.invalid','vendedor',2),
      ('00000000-0000-0000-0000-000000000003','Ajena QA','ajena@qa.invalid','operario',3);
    insert into producto(id,nombre,unidad_base) values(1,'Producto QA','UNIDAD');
    insert into presentacion(id,producto_id,nombre,factor_unidad_base,es_base) values(1,1,'Unidad',1,true),(2,1,'Caja',10,false);
    insert into ubicacion(id,codigo_zona,sucursal_id,es_recepcion,excluye_disponible) values(1,'ORIGEN',1,true,false),(2,'DESTINO',2,true,false);
    select registrar_entrada(1,1,100,'QA','QA');set role authenticated;`);
  const login = n => db.query("select set_config('request.jwt.claim.sub',$1,false)",[`00000000-0000-0000-0000-${String(n).padStart(12,'0')}`]);
  const create = async qty => (await db.query(`select crear_solicitud_traslado('REPOSICION',$1::jsonb,'Identidad no confiable') id`,[JSON.stringify([{producto_id:1,cantidad_base:qty}])])).rows[0].id;
  const dispatch = async(id,lines=null) => (await db.query(`select despachar_traslado($1,'QA',$2::jsonb) result`,[id,lines===null?null:JSON.stringify(lines)])).rows[0].result;
  const receive = async(id,lines=null) => (await db.query(`select recibir_traslado($1,'QA',$2::jsonb) result`,[id,lines===null?null:JSON.stringify(lines)])).rows[0].result;
  const recover = async id => (await db.query(`select recuperar_faltantes_traslado($1,'QA') result`,[id])).rows[0].result;
  const count = async table => Number((await db.query(`select count(*) n from ${table}`)).rows[0].n);
  const stock = async loc => Number((await db.query('select cantidad_base from stock_actual where producto_id=1 and ubicacion_id=$1',[loc])).rows[0]?.cantidad_base || 0);
  const lineId = async id => (await db.query('select id from solicitud_traslado_linea where solicitud_id=$1 order by id',[id])).rows[0].id;

  await login(2);const id=await create(5);const line=await lineId(id);
  assert.equal((await db.query('select solicitado_por from solicitud_traslado where id=$1',[id])).rows[0].solicitado_por,'Vende QA');
  await assert.rejects(()=>dispatch(id),/perfil no permite/);
  await login(3);await assert.rejects(()=>dispatch(id),/sucursal asignada/);await assert.rejects(()=>create(1),/sucursal asignada/);
  await login(1);
  const initial=await count('kardex_transacciones');
  for(const [payload,pattern] of [
    [[{linea_id:line,accion:'DESPACHAR',cantidad_base:8}],/supera lo solicitado/],
    [[{linea_id:line,accion:'DESPACHAR',cantidad_base:0}],/necesita una acción/],
    [[{linea_id:line,accion:'OTRA'}],/Acción/],
    [[{linea_id:line},{linea_id:line}],/repetidas/],
    [[{linea_id:99999}],/ajenas/],
  ]) await assert.rejects(()=>dispatch(id,payload),pattern);
  assert.equal(await count('kardex_transacciones'),initial);assert.equal(await stock(1),100);
  const partial=await dispatch(id,[{linea_id:line,accion:'DESPACHAR',cantidad_base:3}]);
  assert.equal(partial.estado,'EN_TRANSITO');assert.equal(Number(partial.parciales[0].saldo),2);assert.ok(partial.tanda_faltante_id);
  assert.equal(await stock(1),97);assert.equal(await stock(2),3);
  await assert.rejects(()=>dispatch(id),/estado EN_TRANSITO/);
  await assert.rejects(()=>receive(id),/sucursal asignada/);
  await login(2);
  await assert.rejects(()=>receive(id,[{linea_id:line,cantidad_base:4}]),/inválida/);
  await assert.rejects(()=>receive(id,[{linea_id:line,cantidad_base:2},{linea_id:line,cantidad_base:2}]),/repetidas/);
  await receive(id,[{linea_id:line,cantidad_base:2}]);assert.equal(await stock(2),2);
  const afterReceive=await count('kardex_transacciones');await assert.rejects(()=>receive(id),/no se puede recibir/);
  assert.equal(await count('kardex_transacciones'),afterReceive);
  console.log('OK: permisos, identidad, límites, payloads inválidos, parcial con saldo y recepción sin duplicación');

  const shortage=await create(200);await login(1);const blocked=await dispatch(shortage);
  assert.equal(blocked.estado,'CANCELADO');assert.equal(blocked.bloqueadas_por_stock.length,1);assert.ok(blocked.tanda_faltante_id);
  assert.equal(await count('kardex_transacciones'),afterReceive);
  const legacy=await create(10);const legacyLine=await lineId(legacy);
  await db.query("update solicitud_traslado set estado='EN_TRANSITO' where id=$1",[legacy]);
  await login(2);await assert.rejects(()=>receive(legacy),/líneas antiguas/);await assert.rejects(()=>recover(legacy),/perfil no permite/);
  await login(1);const beforeRecovery=await count('kardex_transacciones');
  const recovered=await recover(legacy);assert.equal(recovered.recuperadas,1);assert.equal(recovered.stock_modificado,false);
  const old=(await db.query('select * from solicitud_traslado_linea where id=$1',[legacyLine])).rows[0];
  assert.equal(old.estado,'CAMBIADA');assert.ok(old.reemplazada_por_id);
  const replacement=(await db.query('select * from solicitud_traslado_linea where id=$1',[old.reemplazada_por_id])).rows[0];
  assert.equal(Number(replacement.cantidad_base),10);assert.equal(replacement.solicitud_id,recovered.tanda_faltante_id);
  const headers=await count('solicitud_traslado');assert.equal((await recover(legacy)).recuperadas,0);assert.equal(await count('solicitud_traslado'),headers);
  assert.equal(await count('kardex_transacciones'),beforeRecovery);
  const inconsistent=await create(2);await db.query("update solicitud_traslado set estado='EN_TRANSITO' where id=$1;",[inconsistent]);
  await db.query('update solicitud_traslado_linea set cantidad_despachada=1 where solicitud_id=$1',[inconsistent]);
  await assert.rejects(()=>recover(inconsistent),/conciliación manual/);
  console.log('OK: cancelación sin envío, recuperación enlazada e idempotente sin tocar stock, protección de casos inconsistentes');
} finally { await db.close(); }
